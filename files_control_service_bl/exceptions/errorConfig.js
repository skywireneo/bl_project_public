/**
 * Расширенная конфигурация системы обработки ошибок
 * 
 * Этот файл содержит флаги-константы для управления поведением системы ошибок.
 * Измените значения флагов в зависимости от ваших требований.
 * 
 * Рекомендуемые настройки:
 * - Разработка: все флаги = true (максимум информации)
 * - Продакшен: INCLUDE_STACK_TRACE = false, INCLUDE_CONTEXT = false
 */

module.exports = {
    /**
     * Включать ли stack trace в ответ API
     * true - показывать трейс (для разработки/отладки)
     * false - скрывать трейс (для продакшена)
     */
    INCLUDE_STACK_TRACE: true,

    /**
     * Применять ли sanitization к stack trace (очистка чувствительных данных)
     * true - убирать пароли, токены, API ключи из стека
     * false - показывать стек как есть
     * 
     * ВАЖНО: Рекомендуется всегда держать true для безопасности
     */
    SANITIZE_STACK_TRACE: true,

    /**
     * Включать ли timestamp (время возникновения ошибки) в ответ
     * true - добавлять метку времени
     * false - не добавлять
     */
    INCLUDE_TIMESTAMP: true,

    /**
     * Включать ли request ID в ответ (если доступен)
     * true - добавлять ID запроса для трейсинга
     * false - не добавлять
     */
    INCLUDE_REQUEST_ID: true,

    /**
     * Включать ли путь запроса в ответ об ошибке
     * true - добавлять URL и HTTP метод запроса
     * false - не добавлять
     */
    INCLUDE_REQUEST_PATH: true,

    /**
     * Включать ли контекстную информацию (userAgent, IP, referer и т.п.)
     * true - добавлять информацию о клиенте
     * false - не добавлять
     * 
     * Включает: userAgent, ip, referer, acceptLanguage
     */
    INCLUDE_CONTEXT: true,

    /**
     * Включать ли оригинальную ошибку при error chaining
     * true - показывать цепочку ошибок (originalError)
     * false - показывать только текущую ошибку
     * 
     * Полезно для отладки внешних API ошибок
     */
    INCLUDE_ORIGINAL_ERROR: true,

    /**
     * Показывать ли детальную информацию о внутренних ошибках
     * true - показывать детали (для отладки)
     * false - показывать только общее сообщение (для продакшена)
     */
    SHOW_INTERNAL_ERROR_DETAILS: true,

    /**
     * Язык сообщений об ошибках по умолчанию
     * 'ru' - русский
     * 'en' - английский
     */
    DEFAULT_LANGUAGE: 'ru'
};
